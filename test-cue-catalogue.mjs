import assert from 'node:assert/strict';
import {CueCatalogue} from './cue-catalogue.mjs';
const c=new CueCatalogue();
const cue=(number,list=1,part=0)=>({number,list,part,name:number});
c.begin(1,2);c.add(cue('1'),0);c.add(cue('139'),1);
c.begin(2,1);c.add(cue('5',2),0);
const before=[...c.values()];
c.begin(1,3);c.add(cue('2'),0);c.add(cue('2'),0);
assert.deepEqual([...c.values()],before,'Partial/duplicate replies must not remove the current row');
c.add(cue('139'),1);
assert.deepEqual([...c.values()],before,'Keep old list until all indices arrive');
c.add(cue('139',1,1),2);
assert.deepEqual([...c.values()].filter(x=>x.list===1).map(x=>[x.number,x.part]),[['2',0],['139',0],['139',1]]);
assert.equal([...c.values()].find(x=>x.list===2).number,'5');
c.begin(1,0);assert.deepEqual([...c.values()],[cue('5',2)]);
c.begin(1,2);c.add(cue('10'),0);c.add(cue('20'),1);
const complete=[...c.values()];
c.begin(1,3);c.add(cue('11'),0);
c.reconnect([1,2]);
assert.deepEqual([...c.values()],complete,'Reconnect must retain complete published lists');
c.add(cue('99'),1);
assert.deepEqual([...c.values()],complete,'Replies from interrupted refresh must not change published lists');
c.begin(1,2);c.add(cue('10'),0);
assert.deepEqual([...c.values()],complete,'Reconnect reload must remain atomic');
c.add(cue('21'),1);
assert.deepEqual([...c.values()].filter(x=>x.list===1).map(x=>x.number),['10','21']);
c.reconnect([2]);assert.deepEqual([...c.values()],[cue('5',2)],'Removed lists must not be retained');
console.log('PASS: atomic refresh, duplicate replies, cue parts, deletion and independent lists');
